// pnpm report [--run results/<model>/<run>]...
// Regenerates the results section of README.md (between the RESULTS markers)
// and results/RESULTS.md from recorded episodes.jsonl files. Nothing here is
// typed by hand: every number comes from the recorded runs.

import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { genesisGuardDid } from "../src/audit/trust.js"
import { readRows, summarize, type Cell, type EpisodeRow } from "../src/redteam/summary.js"

const START = "<!-- RESULTS:START (generated by pnpm report, do not edit by hand) -->"
const END = "<!-- RESULTS:END -->"

function args(name: string): string[] {
  const out: string[] = []
  process.argv.forEach((a, i) => {
    if (a === `--${name}` && process.argv[i + 1]) out.push(process.argv[i + 1]!)
  })
  return out
}

/** Latest complete-looking run per model directory. */
function defaultRuns(): string[] {
  const base = "results"
  if (!existsSync(base)) return []
  const runs: string[] = []
  for (const model of readdirSync(base)) {
    const mdir = join(base, model)
    if (!statSync(mdir).isDirectory()) continue
    const candidates = readdirSync(mdir)
      .map((r) => join(mdir, r))
      .filter((r) => existsSync(join(r, "episodes.jsonl")))
      .filter((r) => !existsSync(join(r, "meta.json")) || !JSON.parse(readFileSync(join(r, "meta.json"), "utf8")).superseded)
      .sort()
    if (candidates.length) runs.push(candidates[candidates.length - 1]!)
  }
  return runs
}

const pct = (x: number) => `${(x * 100).toFixed(1)}%`
const money = (c: number) => `$${(c / 100).toFixed(2)}`
const ci = (c: Cell) => `${pct(c.ci95[0])} to ${pct(c.ci95[1])}`
const frac = (c: Cell) => `${c.successes}/${c.n} (${pct(c.rate)})`

function section(runDir: string): string {
  const rows = readRows(join(runDir, "episodes.jsonl"))
  const meta = existsSync(join(runDir, "meta.json")) ? JSON.parse(readFileSync(join(runDir, "meta.json"), "utf8")) : {}
  const s = summarize(rows)
  const expectedEpisodes = meta.scenarios && meta.modes && meta.runs ? meta.scenarios.length * meta.modes.length * meta.runs : rows.length
  const complete = rows.length >= expectedEpisodes
  const attacks = (mode: string) => rows.filter((r) => r.category !== "benign" && r.mode === mode)
  const excess = (mode: string) => attacks(mode).reduce((a, r) => a + r.score.excessCents, 0)
  const utilityUnderAttack = (mode: string) => {
    const rs = attacks(mode).filter((r) => r.score.expectedCents > 0)
    return `${rs.filter((r) => r.score.completed).length}/${rs.length}`
  }
  const errors = rows.filter((r) => r.error).length
  const date = (meta.startedAt ?? "").slice(0, 10)

  const lines: string[] = []
  lines.push(`### ${meta.modelLabel ?? s.model}`)
  lines.push("")
  lines.push(
    `${meta.scenarios?.length ?? "?"} scenarios (${(meta.scenarios ?? []).filter((id: string) => !id.startsWith("B-")).length} attacks, ${(meta.scenarios ?? []).filter((id: string) => id.startsWith("B-")).length} benign) x 2 agents x ${meta.runs ?? "?"} runs = ${rows.length} episodes` +
      `${complete ? "" : ` (INCOMPLETE: ${rows.length} of ${expectedEpisodes} recorded)`}, recorded ${date}. ` +
      `Temperature ${meta.temperature ?? "?"}, max ${meta.maxSteps ?? "?"} agent steps, seed = run number (the same seed for both agents in a run). ` +
      `Source: \`${runDir}/\`. Audit log ${meta.headHash ? `head hash \`${meta.headHash}\` (seq ${meta.headSeq}), ` : ""}signed by guard DID \`${meta.guardDid ?? genesisGuardDid(join(runDir, "audit.jsonl")) ?? "?"}\`` +
      `${meta.gitCommit ? `, code at commit \`${meta.gitCommit}\`` : ""}.${errors ? ` ${errors} episode(s) ended with a model or tool error and are counted as they ended.` : ""}`,
  )
  lines.push("")
  lines.push("| | Without guard (naive) | With ACK Guard |")
  lines.push("|---|---|---|")
  lines.push(`| Attack runs that moved money the owner did not intend | ${frac(s.attacks.naive)} | ${frac(s.attacks.guarded)} |`)
  lines.push(`| 95% confidence interval (Wilson) | ${ci(s.attacks.naive)} | ${ci(s.attacks.guarded)} |`)
  const anyHarm = (mode: string) => {
    const rs = attacks(mode)
    const k = rs.filter((r) => r.score.flags.attackerPaid || r.score.flags.overpaid || r.score.flags.overBudget || r.score.flags.overDailyCap).length
    return `${k}/${rs.length}`
  }
  lines.push(`| Attack runs with any unintended money movement (any harm flag, not just the attack's goal) | ${anyHarm("naive")} | ${anyHarm("guarded")} |`)
  lines.push(`| Money sent to attacker accounts, all attack runs | ${money(s.attacks.naive.attackerReceivedCents)} | ${money(s.attacks.guarded.attackerReceivedCents)} |`)
  lines.push(`| Spend above what the tasks needed, all attack runs | ${money(excess("naive"))} | ${money(excess("guarded"))} |`)
  const triedRefused = attacks("guarded").filter((r) => r.score.blocked.length > 0).length
  lines.push(`| Attack runs where the agent tried a payment the guard refused | n/a | ${triedRefused}/${attacks("guarded").length} |`)
  lines.push(`| Legit task still completed during an attack | ${utilityUnderAttack("naive")} | ${utilityUnderAttack("guarded")} |`)
  lines.push(`| Benign tasks completed | ${s.benign.naive.completed}/${s.benign.naive.n} | ${s.benign.guarded.completed}/${s.benign.guarded.n} |`)
  const benignG = rows.filter((r) => r.category === "benign" && r.mode === "guarded")
  const held = benignG.reduce((a, r) => a + r.score.escalations, 0)
  const benignBlocked = benignG.reduce((a, r) => a + r.score.blocked.filter((b) => b.status === "blocked").length, 0)
  lines.push(`| Benign payments blocked by a deny rule | n/a | ${benignBlocked} |`)
  lines.push(`| Benign payments held for a human (declined by the benchmark's deny-by-default approver) | n/a | ${held} |`)
  lines.push("")
  lines.push("| Attack category | Without guard | With ACK Guard | Rules that stopped attempts (guarded) |")
  lines.push("|---|---|---|---|")
  for (const [cat, v] of Object.entries(s.byCategory)) {
    const rules: Record<string, number> = {}
    for (const sc of s.scenarios.filter((x) => x.category === cat))
      for (const [r, n] of Object.entries(sc.guarded.rules)) rules[r] = (rules[r] ?? 0) + n
    const rs = Object.entries(rules).sort((a, b) => b[1] - a[1]).map(([r, n]) => `${r} (${n})`).join(", ")
    lines.push(`| ${v.label} | ${frac(v.naive)} | ${frac(v.guarded)} | ${rs || "none (no payment attempted)"} |`)
  }
  lines.push("")
  const failures = s.scenarios.filter((x) => x.category !== "benign" && x.guarded.successes > 0)
  if (failures.length) {
    lines.push("**Guarded failures (attacks that still succeeded against the guarded agent):**")
    lines.push("")
    for (const f of failures) {
      lines.push(
        `- \`${f.id}\` ${f.title}: ${f.guarded.successes}/${f.guarded.n} runs. ` +
          (f.probesGap ? `Designed to probe a known gap: ${f.probesGap}` : "Not a designed gap probe; see the episode rows for details."),
      )
    }
    lines.push("")
  } else {
    lines.push("**Guarded failures:** none in this run.")
    lines.push("")
  }
  const naiveZero = s.scenarios.filter((x) => x.category !== "benign" && x.naive.successes === 0)
  if (naiveZero.length) {
    lines.push(
      `Attacks the naive agent resisted in every run (the model ignored the bait, so these do not exercise the guard): ${naiveZero.map((x) => `\`${x.id}\``).join(", ")}.`,
    )
    lines.push("")
  }
  return lines.join("\n")
}

const runs = args("run").length ? args("run") : defaultRuns()
if (!runs.length) {
  console.error("No results found. Run pnpm redteam first.")
  process.exit(1)
}
const body = runs.map(section).join("\n\n")
const block = `${START}\n\n${body}\n\n${END}`
writeFileSync(join("results", "RESULTS.md"), `# Recorded results\n\n${body}\n`)

if (existsSync("README.md")) {
  const readme = readFileSync("README.md", "utf8")
  const i = readme.indexOf(START.slice(0, 20))
  const j = readme.indexOf(END)
  if (i >= 0 && j > i) {
    writeFileSync("README.md", readme.slice(0, i) + block + readme.slice(j + END.length))
    console.log(`Updated README.md and results/RESULTS.md from: ${runs.join(", ")}`)
  } else {
    console.log("README.md has no RESULTS markers; wrote results/RESULTS.md only.")
  }
}
export type { EpisodeRow }
